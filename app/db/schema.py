"""DDL: table creation and idempotent column migrations."""

DDL = """
-- ============================================================
-- ACCOUNTS  — login credentials, one row per portal user
-- ============================================================
CREATE TABLE IF NOT EXISTS accounts (
    username        TEXT        PRIMARY KEY,
    role            TEXT        NOT NULL CHECK (role IN ('authority', 'inspector')),
    display_name    TEXT        NOT NULL,
    password_salt   TEXT        NOT NULL,
    password_hash   TEXT        NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- USERS  — inspector profiles, linked to an account after approval
-- ============================================================
CREATE TABLE IF NOT EXISTS users (
    id                      INTEGER     PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username                TEXT        REFERENCES accounts(username) ON DELETE SET NULL,
    temp_password           TEXT,
    name                    TEXT        NOT NULL,
    email                   TEXT        NOT NULL DEFAULT '',
    phone                   TEXT        NOT NULL DEFAULT '',
    designation             TEXT        NOT NULL DEFAULT '',
    specialization          TEXT        NOT NULL DEFAULT '',
    region                  TEXT        NOT NULL DEFAULT '',
    department_unit         TEXT        NOT NULL DEFAULT 'Inspection Department',
    jurisdiction            TEXT        NOT NULL DEFAULT '',
    qualifications          TEXT        NOT NULL DEFAULT '',
    experience_years        INTEGER     CHECK (experience_years >= 0),
    bio                     TEXT        NOT NULL DEFAULT '',
    official_id             TEXT,
    official_id_verified    BOOLEAN     NOT NULL DEFAULT FALSE,
    active                  BOOLEAN     NOT NULL DEFAULT TRUE,
    status                  TEXT        CHECK (status IN ('Pending', 'Verified', 'Flagged')),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_official_id
    ON users(official_id) WHERE official_id IS NOT NULL AND official_id <> '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email
    ON users(email) WHERE email <> '';

-- ============================================================
-- ORGANIZATIONS  — registered NGOs / entities under inspection
-- ============================================================
CREATE TABLE IF NOT EXISTS organizations (
    id                      TEXT        PRIMARY KEY,
    name                    TEXT        NOT NULL UNIQUE,
    reg                     TEXT        NOT NULL UNIQUE,
    location                TEXT        NOT NULL,
    address                 TEXT        NOT NULL,
    verification            TEXT        NOT NULL DEFAULT 'Pending'
                                        CHECK (verification IN ('Pending', 'Verified', 'Flagged')),
    risk                    TEXT        NOT NULL DEFAULT 'Review',
    latitude                REAL,
    longitude               REAL,
    radius_m                REAL        CHECK (radius_m > 0),
    contact_email           TEXT,
    contact_person          TEXT,
    contact_email_verified  BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- INSPECTION REQUESTS  — public department submissions
-- ============================================================
CREATE TABLE IF NOT EXISTS inspection_requests (
    id                  TEXT        PRIMARY KEY,
    department          TEXT        NOT NULL,
    requester_name      TEXT        NOT NULL DEFAULT '',
    requester_email     TEXT        NOT NULL DEFAULT '',
    requester_verified  BOOLEAN     NOT NULL DEFAULT FALSE,
    organization_id     TEXT        REFERENCES organizations(id) ON DELETE SET NULL,
    organization_display TEXT,
    purpose             TEXT        NOT NULL DEFAULT '',
    scope               TEXT        NOT NULL DEFAULT '',
    urgency             TEXT        NOT NULL DEFAULT 'Routine'
                                    CHECK (urgency IN ('Routine', 'Time-sensitive', 'Urgent')),
    status              TEXT        NOT NULL DEFAULT 'Pending'
                                    CHECK (status IN ('Pending', 'Approved', 'Rejected')),
    reviewed_by         TEXT        REFERENCES accounts(username) ON DELETE SET NULL,
    reviewed_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_inspection_requests_status_created
    ON inspection_requests(status, created_at);

-- ============================================================
-- SCHEDULES  — assigned inspection appointments
-- ============================================================
CREATE TABLE IF NOT EXISTS schedules (
    id                      TEXT        PRIMARY KEY,
    organization            TEXT        NOT NULL,
    location                TEXT        NOT NULL,
    inspector               TEXT        NOT NULL,
    organization_id         TEXT        REFERENCES organizations(id) ON DELETE SET NULL,
    inspector_id            INTEGER     REFERENCES users(id) ON DELETE SET NULL,
    inspection_request_id   TEXT        REFERENCES inspection_requests(id) ON DELETE SET NULL,
    date                    DATE        NOT NULL,
    time                    TIME        NOT NULL,
    purpose                 TEXT,
    scope                   TEXT,
    status                  TEXT        NOT NULL DEFAULT 'Scheduled'
                                        CHECK (status IN ('Scheduled', 'Completed', 'Cancelled')),
    site_latitude           REAL,
    site_longitude          REAL,
    site_radius_m           REAL        CHECK (site_radius_m > 0),
    organization_notified   BOOLEAN     NOT NULL DEFAULT FALSE,
    notification_status     TEXT        NOT NULL DEFAULT 'not_requested',
    notification_error      TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_schedules_date       ON schedules(date);
CREATE INDEX IF NOT EXISTS idx_schedules_inspector  ON schedules(inspector_id);
CREATE INDEX IF NOT EXISTS idx_schedules_org        ON schedules(organization_id);

-- ============================================================
-- INSPECTIONS  — submitted / completed inspection records
-- ============================================================
CREATE TABLE IF NOT EXISTS inspections (
    id                      TEXT        PRIMARY KEY,
    organization            TEXT        NOT NULL,
    location                TEXT        NOT NULL,
    inspector               TEXT        NOT NULL,
    schedule_id             TEXT        REFERENCES schedules(id) ON DELETE SET NULL,
    date                    DATE        NOT NULL,
    time                    TIME        NOT NULL,
    scheduled_date          DATE,
    scheduled_time          TIME,
    status                  TEXT        NOT NULL DEFAULT 'Submitted'
                                        CHECK (status IN ('Submitted', 'Verified', 'Flagged')),
    notes                   TEXT,
    latitude                REAL,
    longitude               REAL,
    location_accuracy_m     REAL        CHECK (location_accuracy_m >= 0),
    location_captured_at    TIMESTAMPTZ,
    location_distance_m     REAL,
    location_verified       BOOLEAN,
    location_check_status   TEXT,
    photo_media_id          TEXT        REFERENCES evidence_media(media_id) ON DELETE SET NULL,
    photo_captured_at       TIMESTAMPTZ,
    submitted_at            TIMESTAMPTZ,
    client_submission_id    TEXT        UNIQUE
);
CREATE INDEX IF NOT EXISTS idx_inspections_date     ON inspections(date);
CREATE INDEX IF NOT EXISTS idx_inspections_schedule ON inspections(schedule_id);

-- ============================================================
-- EVIDENCE MEDIA  — binary photo/video blobs
-- ============================================================
CREATE TABLE IF NOT EXISTS evidence_media (
    media_id    TEXT    PRIMARY KEY,
    media_type  TEXT    NOT NULL,
    content     BYTEA   NOT NULL
);

-- ============================================================
-- DELETED INSPECTIONS  — tombstone for inspector app sync
-- ============================================================
CREATE TABLE IF NOT EXISTS deleted_inspections (
    id          TEXT        PRIMARY KEY,
    deleted_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- NOTIFICATION OUTBOX  — retry queue for schedule emails
-- ============================================================
CREATE TABLE IF NOT EXISTS inspection_notification_outbox (
    schedule_id     TEXT        PRIMARY KEY REFERENCES schedules(id) ON DELETE CASCADE,
    status          TEXT        NOT NULL,
    attempts        INTEGER     NOT NULL DEFAULT 0,
    recipient_email TEXT,
    last_error      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at    TIMESTAMPTZ
);

-- ============================================================
-- RATE LIMITS  — sliding window for public request submissions
-- ============================================================
CREATE TABLE IF NOT EXISTS inspection_request_rate_limits (
    bucket_key      TEXT        NOT NULL,
    window_start    TIMESTAMPTZ NOT NULL,
    request_count   INTEGER     NOT NULL,
    PRIMARY KEY (bucket_key, window_start)
);

-- ============================================================
-- PORTAL DATA / SETTINGS  — authority UI preferences (JSON blobs)
-- ============================================================
CREATE TABLE IF NOT EXISTS portal_data (
    data_key    TEXT    PRIMARY KEY,
    payload     TEXT    NOT NULL
);
CREATE TABLE IF NOT EXISTS portal_settings (
    setting_id  INTEGER PRIMARY KEY CHECK (setting_id = 1),
    payload     TEXT    NOT NULL
);

-- ============================================================
-- REVERSE GEOCODE CACHE  — Nominatim response cache
-- ============================================================
CREATE TABLE IF NOT EXISTS reverse_geocode_cache (
    cache_key   TEXT        PRIMARY KEY,
    payload     TEXT        NOT NULL,
    cached_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
"""

